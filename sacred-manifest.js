// Build docs/sacredFourteen/sacred-fourteen.json and .md: what was added to each patient and the answer key for the AI summary.
// Usage: node sacred-manifest.js --dfn <dfn> [--dfn <dfn> ...]   (merges into the existing files; other patients are kept)
// Inputs: plans/dfn<dfn>-visits.json, plans/dfn<dfn>-labs-vitals.json, plans/dfn<dfn>-answerkey.json, logs/import-<dfn>.json,
// docs/lighthouse-review/dfn-<dfn>.json, and the patient's VPR (to see what is booked, noted or already there).
const fs = require('fs');
const path = require('path');
require('./src/config');
const { callRpc } = require('./src/vistaApiClient');

const DIR = path.join(__dirname, 'docs', 'sacredFourteen');
const JSON_FILE = path.join(DIR, 'sacred-fourteen.json');
const MD_FILE = path.join(DIR, 'sacred-fourteen.md');
const arg = (n) => process.argv.flatMap((a, i) => (a === n ? [process.argv[i + 1]] : []));
const dom = (i) => i.uid.split(':')[2];
const day = (v) => { const s = String(v || '').replace(/\D/g, ''); return s.length >= 8 ? `${s.slice(0, 4)}-${s.slice(4, 6)}-${s.slice(6, 8)}` : ''; };
const readJson = (f, d) => (fs.existsSync(f) ? JSON.parse(fs.readFileSync(f, 'utf8')) : d);

async function entry(dfn) {
  const visitsPlan = readJson(path.join(__dirname, 'plans', `dfn${dfn}-visits.json`), { visits: [] });
  const lv = readJson(path.join(__dirname, 'plans', `dfn${dfn}-labs-vitals.json`), { vitals: [], labs: [], panels: [] });
  const key = readJson(path.join(__dirname, 'plans', `dfn${dfn}-answerkey.json`), null);
  const imp = readJson(path.join(__dirname, 'logs', `import-${dfn}.json`), []);
  const review = readJson(path.join(__dirname, 'docs', 'lighthouse-review', `dfn-${dfn}.json`), null);
  const roster = review ? review.roster : {};
  const body = await callRpc('VPR GET PATIENT DATA JSON', [{ namedArray: { patientId: dfn } }], 'CDSP RPC CONTEXT', { jsonResult: true, timeout: 120000, raw: true });
  const items = (body.payload && body.payload.data && body.payload.data.items) || [];
  const p = items.find((i) => dom(i) === 'patient') || {};
  const have = new Set(items.filter((i) => dom(i) === 'visit' || dom(i) === 'appointment').map((i) => `${day(i.dateTime)}|${i.locationName}`));
  const notes = new Set(items.filter((i) => dom(i) === 'document').map((d) => day(d.referenceDateTime)));
  const planned = new Set(visitsPlan.visits.map((v) => `${v.date}|${v.clinic}`));
  const okImports = imp.filter((x) => /^1/.test(String(x.reply))).length;
  const noise = items.filter((i) => dom(i) === 'visit' && !planned.has(`${day(i.dateTime)}|${i.locationName}`))
    .map((v) => ({ date: day(v.dateTime), clinic: v.locationName, reason: v.reasonName || '' })).sort((a, b) => a.date.localeCompare(b.date));
  return {
    dfn, name: p.fullName, icn: roster.icn, preparedAt: new Date().toISOString().slice(0, 10),
    stages: {
      labsVitalsImported: `${okImports} of ${lv.vitals.length + lv.labs.length + lv.panels.length} calls succeeded (logs/import-${dfn}.json)`,
      visitsBooked: visitsPlan.visits.filter((v) => have.has(`${v.date}|${v.clinic}`)).length + ` of ${visitsPlan.visits.length}`,
      notesFiled: visitsPlan.visits.filter((v) => notes.has(v.date)).length + ` of ${visitsPlan.visits.length}`,
    },
    visits: visitsPlan.visits.map((v) => ({ date: v.date, time: v.time, clinic: v.clinic, reason: v.presenting[0], icd: v.visitDiagnoses[0].icd, sentinel: !!v.sentinel, booked: have.has(`${v.date}|${v.clinic}`), noteFiled: notes.has(v.date) })),
    vitals: lv.vitals.map((v) => ({ at: v.at, location: v.location, type: v.type, value: v.value })),
    labs: lv.labs.map((l) => ({ at: l.at, location: l.location, test: l.test, value: l.value })),
    panels: lv.panels.map((l) => ({ at: l.at, location: l.location, panel: l.panel, values: l.values })),
    outpatientLabsNoVisit: visitsPlan.extraLabs ? { date: visitsPlan.extraLabs.date, time: visitsPlan.extraLabs.time } : null,
    medications: items.filter((i) => dom(i) === 'med').sort((a, b) => String(a.overallStart).localeCompare(String(b.overallStart))).map((m) => ({
      drug: m.name, dose: ((m.dosages || [])[0] || {}).dose, schedule: ((m.dosages || [])[0] || {}).schedule || ((m.dosages || [])[0] || {}).scheduleName, sig: m.sig,
      start: day(m.overallStart), expires: day(m.overallStop), status: m.vaStatus, fills: (m.fills || []).map((f) => day(f.dispenseDate || f.fillDate || f.releaseDate)).filter(Boolean),
    })),
    preExistingVisitsNotFromUs: noise,
    answerKey: key,
  };
}

function markdown(all) {
  const L = ['# Sacred fourteen: generated history and answer keys', '',
    'What was added to each important test patient, and what an AI summary of the record should (and should not) say. Generated by `sacred-manifest.js` from `plans/` and the patient\'s VPR; data is in `sacred-fourteen.json`.', ''];
  for (const e of Object.values(all.patients)) {
    L.push(`## ${e.name} (DFN ${e.dfn}, ICN ${e.icn})`, '', `Prepared ${e.preparedAt}. Stages: labs and vitals ${e.stages.labsVitalsImported}; visits booked ${e.stages.visitsBooked}; notes filed ${e.stages.notesFiled}.`, '');
    L.push('### Added', '', '| Date | Time | Clinic | Reason | ICD | Critical event | Booked | Note |', '|---|---|---|---|---|---|---|---|');
    for (const v of e.visits) L.push(`| ${v.date} | ${v.time} | ${v.clinic} | ${v.reason} | ${v.icd} | ${v.sentinel ? 'yes' : ''} | ${v.booked ? 'yes' : 'no'} | ${v.noteFiled ? 'yes' : 'no'} |`);
    if (e.outpatientLabsNoVisit) L.push('', `Outpatient labs without a visit: ${e.outpatientLabsNoVisit.date} ${e.outpatientLabsNoVisit.time} (location LABORATORY).`);
    const dates = [...new Set([...e.vitals.map((v) => v.at.slice(0, 10)), ...e.labs.map((v) => v.at.slice(0, 10)), ...e.panels.map((v) => v.at.slice(0, 10))])].sort();
    L.push('', '### Vitals and labs by day', '', '| Date | Vitals | Labs |', '|---|---|---|');
    for (const d of dates) {
      const vit = e.vitals.filter((v) => v.at.startsWith(d)).map((v) => `${v.type} ${v.value}`).join('; ');
      const lab = [...e.labs.filter((v) => v.at.startsWith(d)).map((v) => `${v.test} ${v.value}`), ...e.panels.filter((v) => v.at.startsWith(d)).map((v) => `${v.panel}: ${Object.entries(v.values).map(([k, x]) => `${k} ${x}`).join(', ')}`)].join('; ');
      L.push(`| ${d} | ${vit} | ${lab} |`);
    }
    if (e.medications && e.medications.length) {
      L.push('', '### Medications (from the record)', '', '| Drug | Dose | Schedule | Started | Expires | Status | Fill dates |', '|---|---|---|---|---|---|---|');
      for (const m of e.medications) L.push(`| ${m.drug} | ${m.dose || ''} | ${m.schedule || ''} | ${m.start} | ${m.expires} | ${m.status} | ${m.fills.join(', ')} |`);
    }
    if (e.preExistingVisitsNotFromUs.length) L.push('', `### Already in the record (not added by us)`, '', `${e.preExistingVisitsNotFromUs.length} visits, for example: ` + e.preExistingVisitsNotFromUs.slice(-6).map((v) => `${v.date} ${v.clinic}`).join('; ') + '.');
    if (e.answerKey) {
      const k = e.answerKey;
      L.push('', '### Answer key', '', `Summary expected for: ${k.summaryFor} (record as of ${k.summaryAsOf}).`, '', '| ID | Severity | Date | Source | What the summary must surface |', '|---|---|---|---|---|');
      for (const i of k.keyItems) L.push(`| ${i.id} | ${i.severity} | ${i.date} | ${i.source} | ${i.finding} |`);
      L.push('', '**Must not overstate (routine):**', ...k.distractors.map((d) => `- ${d}`), '', '**Must not say:**', ...k.shouldNotSay.map((d) => `- ${d}`));
      if (k.scoring) {
        L.push('', '### Scoring rules', '', `- **Found:** ${k.scoring.found}`, `- **Partial:** ${k.scoring.partial}`, `- **Missed:** ${k.scoring.missed}`, `- **Accurate:** ${k.scoring.accurate}`, `- **Noise:** ${k.scoring.noise}`, `- **Pass threshold:** ${k.scoring.passThreshold}`);
        const ruled = k.keyItems.filter((i) => i.scoringRule);
        if (ruled.length) {
          L.push('', '| ID | Found | Partial | Missed |', '|---|---|---|---|', ...ruled.map((i) => `| ${i.id} | ${i.scoringRule.found} | ${i.scoringRule.partial} | ${i.scoringRule.missed} |`));
        }
      }
      L.push('', '### Scoring (fill in when the summary comes back)', '', '| ID | Found | Accurate | Notes |', '|---|---|---|---|', ...k.keyItems.map((i) => `| ${i.id} | | | |`));
      for (const run of k.runs || []) {
        const by = Object.fromEntries(run.scores.map((s) => [s.id, s]));
        L.push('', `#### Summary run ${run.date} (window ${run.window}): ${run.score}`, '', run.note, '', '| ID | Found | Accurate | Notes |', '|---|---|---|---|',
          ...k.keyItems.map((i) => `| ${i.id} | ${(by[i.id] || {}).found || ''} | ${(by[i.id] || {}).accurate || ''} | ${(by[i.id] || {}).notes || ''} |`),
          '', '**Observations:**', ...run.observations.map((o) => `- ${o}`));
      }
    }
    L.push('');
  }
  return L.join('\n');
}

(async () => {
  const dfns = arg('--dfn');
  if (!dfns.length) throw new Error('Usage: node sacred-manifest.js --dfn <dfn> [--dfn <dfn>]');
  fs.mkdirSync(DIR, { recursive: true });
  const all = readJson(JSON_FILE, { description: 'Generated history and answer keys for the sacred fourteen test patients', patients: {} });
  for (const d of dfns) all.patients[d] = await entry(d);
  fs.writeFileSync(JSON_FILE, JSON.stringify(all, null, 2));
  fs.writeFileSync(MD_FILE, markdown(all));
  console.log(`Wrote docs/sacredFourteen/sacred-fourteen.json and .md for ${Object.keys(all.patients).join(', ')}`);
})().catch((e) => { console.error(`FAIL ${e.message}`); process.exit(1); });
